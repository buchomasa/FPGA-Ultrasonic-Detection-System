`timescale 1ns/1ps

module csm_row_testbench;

    reg  [31:0] a;
    reg  [31:0] b;
    reg         bi;
    reg         os;

    wire [31:0] d;
    wire        bo;

    csm_row_32 DUT (
        .a(a),
        .b(b),
        .bi(bi),
        .os(os),
        .d(d),
        .bo(bo)
    );

    initial begin

        //--------------------------------------------------
        // Force subtract mode
        //--------------------------------------------------
        os = 1'b0;
        bi = 1'b0;

        //--------------------------------------------------
        // Test 1
        //--------------------------------------------------
        a = 32'd25;
        b = 32'd1;
        #10;

        $display("25 - 1");
        $display("d=%0d bo=%b", d, bo);

        //--------------------------------------------------
        // Test 2
        //--------------------------------------------------
        a = 32'd25;
        b = 32'd25;
        #10;

        $display("25 - 25");
        $display("d=%0d bo=%b", d, bo);

        //--------------------------------------------------
        // Test 3
        //--------------------------------------------------
        a = 32'd50;
        b = 32'd20;
        #10;

        $display("50 - 20");
        $display("d=%0d bo=%b", d, bo);

        //--------------------------------------------------
        // Test 4
        //--------------------------------------------------
        a = 32'd1;
        b = 32'd25;
        #10;

        $display("1 - 25");
        $display("d=%0d bo=%b", d, bo);

        //--------------------------------------------------
        // Test 5
        //--------------------------------------------------
        a = 32'd100;
        b = 32'd99;
        #10;

        $display("100 - 99");
        $display("d=%0d bo=%b", d, bo);

        $finish;
